export function* annualReadings(row) {
  const c=contextFor(row);
  for(const [cycleIndex,cycle] of row.daYun.cycles.entries()) {
    const targets=[...c.natal,branches.indexOf(cycle.branch)], decStem=stems.indexOf(cycle.stem);
    for(let step=0;step<10;step++) {
      const year=c.firstJuly+10*cycleIndex+step;
      const si=(year-4)%10, bi=(year-4)%12, gz=stems[si]+branches[bi];
      const age=year-c.birthYear-Number(c.beforeBirthday), name=god(c.master,si);
      const ref=['/id','/dayMaster','/daYun/startDate','/daYun/cycles/'+cycleIndex], contacts=[], joined=[],clashed=[];
      for(const [i,b] of targets.entries()) {
        const kind=bi===b?'同支':(bi+6)%12===b?'相沖':(bi+b)%12===1?'六合':null;
        if(!kind)continue;
        contacts.push(roleLabels[i]+branches[b]+kind);
        if(kind==='六合')joined.push(i);
        if(kind==='相沖')clashed.push(i);
        if(i<4)ref.push('/pillars/'+roles[i]+'/branch');
      }
      if(!contacts.length)ref.push('/pillars');
      const hasBoth=joined.length&&clashed.length;
      const key=hasBoth?'both':clashed.length?'clash':joined.length?'join':contacts.length?'repeat':'none';
      const text1='這一年的'+gz+'，年干'+stems[si]+'對日主'+row.dayMaster+'為'+name+'，可從「'+stemIdeas[name]+'」來讀。'+
        '所在的'+cycle.ganZhi+'運以'+traditional(cycle.stemTenGod)+'為運干十神。'+coupling[(Math.floor(si/2)-Math.floor(decStem/2)+5)%5];
      const named=contacts.length?'歲支'+branches[bi]+'與'+contacts.join('、與')+'。':'';
      const detail=hasBoth?'若套到生活裡，先分辨「'+facets[joined[0]]+'」和「'+facets[clashed[0]]+'」各需要你做什麼。':'';
      yield {year,ganzhi:gz,age,cycleIndex,tenGod:name,contacts,evidence:ref,
        text:text1+'\n\n'+named+touchNotes[key]+detail+'\n\n'+scenes[ageBand(age)][names.indexOf(name)]+'\n\n'+phases[step]};
    }
  }
}
